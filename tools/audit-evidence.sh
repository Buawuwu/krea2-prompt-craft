#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────
# Krea2 库内证据分级审计（v2.14.0 新增）
#   用法: bash tools/audit-evidence.sh [skill根目录]
#
# 为什么有它（2026-09-18 的教训）:
#   手崩的直接诱因「四指并拢」，是库把**一次③段观测（n=1）**写成手部的「正解」，
#   然后被原样照抄进稿子。→ 光写一条"证据分级"的元规则挡不住：
#   **库里已经存在没标级的断言**，读的人无从分辨哪句能抄。
#   所以：**能机器扫的，就不靠人读的时候自己长心眼**（与 check-prompt.sh 同一规矩）。
#
# 判定（只管"能不能抄"这一级）：
#   含 `正解 / 可照抄 / 口诀 / 定式 / 唯一写法 / 唯一有效` 的行 = 可照抄级断言，
#   必须带标记 `【可照抄 · …】` 或 `【仅示意 · 未验】`（或同级的 `【观测 · …】`，v2.19.0 补认）。
#   CHANGELOG.md **不参与**审计——它本来就是"观测区"，n=1 就该待在那儿。
#   ⚠️ 机器只查"有没有标"；"这个 n 够不够升格为通则"由人判。
# ─────────────────────────────────────────────────────────────
set -u
ROOT="${1:-$(cd "$(dirname "$0")/.." && pwd)}"
ASSERT='正解|可照抄|口诀|定式|唯一写法|唯一有效'

total=0; marked=0; unmarked=0
echo "── 证据分级审计：$ROOT"
echo "   （只审"可照抄"级断言；CHANGELOG.md = 观测区，不参与）"
echo
printf "%-30s %-9s %s\n" "文件:行" "等级" "断言片段"
printf '%s\n' "──────────────────────────────────────────────────────────────────────────"
for f in "$ROOT/SKILL.md" "$ROOT"/references/*.md; do
  [ -f "$f" ] || continue
  case "$(basename "$f")" in CHANGELOG.md) continue;; esac
  # 元规则方块整块跳过（那里的「正解 / 可照抄」是在**定义标记语法**，不是在断言画面规律）
  BOX=$(awk '/### 📏 元规则/{s=NR} /^\*\*贯穿全 skill/{if(s){print s"-"NR; exit}}' "$f")
  while IFS= read -r line; do
    ln="${line%%:*}"; txt="${line#*:}"
    if [ -n "$BOX" ] && [ "$ln" -ge "${BOX%-*}" ] && [ "$ln" -le "${BOX#*-}" ]; then continue; fi
    # 排除"不是断言"的行：标题 · 版本摘要条 · 指针行 · 表格行（表格多为速查/记录表，本身带 ✅ 与文件号）
    # ＋ 元规则自身的说明文字（含"元规则"或标记语法 `n≥3` 的行是定义，不是在断言画面规律）
    printf '%s' "$txt" | grep -aqE '^(#|- *\*\*v[0-9]|\||.*`references/)' && continue
    total=$((total+1))
    # 已标级 = 带 `【可照抄…】`（通则）或 `【仅示意…】`（观测，元规则里的等级名）——
    # 也接受 `【观测…】`（v2.19.0 补）：库里 §1.3「画面外的器械」那条从 v2.18.4 起就用这个写法，
    # 意思是"这是观测、不是通则"，与 `【仅示意】` 同级；机器若只认「仅示意」会把它误报成"未标级"。
    if printf '%s' "$txt" | grep -aqE '【(可照抄|仅示意|观测)'; then
      marked=$((marked+1))
      printf "%-30s %-9s %s\n" "$(basename "$f"):$ln" "已标级" "$(printf '%s' "$txt" | grep -oE '【(可照抄|仅示意|观测)[^】]*】' | head -1)"
    else
      unmarked=$((unmarked+1))
      printf "%-30s %-9s %s\n" "$(basename "$f"):$ln" "未标级 ⚠" "$(printf '%s' "$txt" | cut -c1-96)"
    fi
  done < <(grep -anE "$ASSERT" "$f")
done
echo "──────────────────────────────────────────────────────────────────────────"
echo "可照抄级断言 $total 行：**已标级 $marked 行 · 未标级 $unmarked 行**"
echo
echo "※ 未标级的按元规则一律算「【仅示意】· 不得照抄」——所以它们**不危险，只是暂时不好用**；"
echo "  要升格就得补 n 与条件（档位 · 判读段位 · 种子），或降格搬去 CHANGELOG 观测区。"

# ── 不变式：SKILL.md「版本」段体积（v2.17.1 新增）────────────────────────────
# 为什么写成机器查：SKILL.md 是**唯一被自动加载**的文件，版本摘要写在这里＝每次调用都付一次钱。
# v2.9.3 移出过一次（省 31%），v2.10–v2.17 又长回来 10,850 B / 占 14.2% —— 写提醒挡不住，写不成不变式也白搭。
VSZ=$(awk '/^## 版本/{f=1} f' "$ROOT/SKILL.md" | wc -c)
echo
if [ "$VSZ" -gt 1024 ]; then
  echo "❌ Ⓥ SKILL.md「版本」段 = ${VSZ} B（上限 1024 B）—— 摘要只许留在 references/CHANGELOG.md"
else
  echo "✅ Ⓥ SKILL.md「版本」段 = ${VSZ} B（≤ 1024 B）"
fi
exit 0
