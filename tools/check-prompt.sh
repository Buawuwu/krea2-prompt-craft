#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────
# Krea2 出词稿自查 · 出词后**必跑**
#   用法: bash tools/check-prompt.sh <稿子.md>
#
# 为什么有这个脚本（2026-09-13 的教训）:
#   纪律写在文档里**挡不住手滑**——同一天内「禁止式负向句」这一条
#   被违反了两次（一次在电车站牌上失效、一次在 v3 稿里靠自查才抓到）。
#   所以把检查做成**可执行的**，别再靠记性。
#   对应 SKILL.md §1.3 出稿前自查里的硬门槛若干条（禁止式负向句 · 手部两句…）。
#   ③b（v2.9.7.2 补）：跨段矛盾——同句检查抓不到"主体段说整张脸露出、中景段说面罩盖住眼"这类。
#
#   2026-09-13 二轮加固（v2.9.7）：又添 ③④ 两条**机器可查**。
#   起因：科幻女战士一链连出 6 版、两次致死错，而这两条当时的脚本
#   **一条都查不出来**，全靠人眼 → 外流了：
#     ③ 全称替换句：`肩膀以下是整套机械外骨骼` → 模型**照字面删掉**那个人体部位
#     ④ 人物身上的「比…还…」：`肩甲总宽超过她的身高` → 荒谬几何，逼模型把人体缩小
#   规矩：**凡能机器查的错，就不该再靠记性**（禁止式被本脚本抓到过 3 次，一次都没外流）。
#
#   2026-09-18 三轮加固（v2.13.0）：再添 ⑥⑦ 两条**机器可查**。
#   起因：真人试稿「手穿模」外流到用户手上——①段 1152×2048 出图里
#   摊开那只手**四指连成蹼、拇指塌进掌缘**，捏针那只手**糊成一只锥形团块**、
#   手背边缘**扎进白衬衫里没有边界**。而当时的库**不但没拦住，还把肇事的
#   "四指并拢"当成"正解"写进了范例**（`genre-liveaction.md` 手部条）——
#   教训升级：**能被机器查的错，不但不该靠记性，更不该靠人读范例时自己长心眼**。
#     ⑥ 手部糊化词：`并拢 / 合拢 / 指尖挨着掌心` → 手指被糊成一片（出蹼 / 团块）
#     ⑦ 手部接触点：手 + 物件 + 动作同段，却**没写"谁压谁"** → 模型自己编 → 穿模
#
#   2026-10-01 五轮加固（v2.19.25）：再添 ⑫⑬⑭（在 tools/check-form.py 内）——
#   起因：用户「你怎么老是犯同一个错误，写了规范不管用？」。一条形态 A 稿同时踩了
#   「姿势×机位互斥」与「窄边当物锚」，两条规则都写在册里、却没出现在交付物上。
#     ⑫ 姿势×机位互斥对 → 低机位仰拍（出图角度怪）
#     ⑬ 物锚必须是"存在的面"（边沿/悬空 → 锁不住几何）
#     ⑭ 稿首三行元信息（形态选择 · 下缘声明次数 · 挂档→预期年龄读出），缺 = 没交付完
#   配套：tools/check-verdict.sh（⑮ 判语四核）
#
#   2026-10-01 四轮加固（v2.19.22）：再添 ⑩⑪ —— 由 tools/check-form.py 算，**数字不是助手写的**。
#   起因：用户「我是真不理解,每次写十段式都会有问题」「这个 skill 提示词你认错多少次了,屡教不改」。
#   v2.19.18/19/20 三刀都写在 SKILL.md 正文里，**同一个坑照翻**——
#   因为检查项只活在"知识层"、没出现在"交付物"上，而自查是犯错者自己打勾，永远全绿。
#     ⑩ 形态选择：形态 B（有段名）必须在稿首自报理由，**且理由必须被正文自证**；
#        枚举里没有"单人人像" → **单主体走十段必然不过**（单主体默认走形态 A）。
#     ⑪ 下缘声明：「画面下缘 / 最近层 / 底部」全篇只许 1 处。
#        十段里只有「前景」要求新增物件、其余九段描述已有主体，而「构图」也在描述下缘
#        → 模型收到两个版本的"下缘要有个东西" → 自己挑一个执行、挑哪个不可预测
#        （长椅扶手→又大又实 · 色块→悬空一坨 · 衣料下缘→贴片 · 人→被挤到画面下角）。
#
#   2026-10-05 六轮加固（v2.19.28）：再添 ⑰（在 tools/check-form.py 内）——
#   起因：用户「把'不许 beautiful/stunning…'从人读变成机器查」。规格见 references/prose-quality.md §2。
#     ⑰ 水词：正文不许出现空词（美丽/优雅/惊艳/完美…）—— 空词不落到像素上，模型只能自己编。
#        豁免 = 同一「分句」内有 强动词 / 材质 / 光（源只给了「少用或不用，除非紧跟具体动作/材质」）。
#   ⚠️ 落地时抓到的坑（照抄素材的表会做成死代码）：素材的「机器查表 v0」是**英文**表，
#      而 ① 已强制正文零拉丁字母 → 只查英文，命中数**恒为 0**。
#      → ⑰ 主查**中文对照表 v1**（由 §2.3「空词→落地改写」反推 29 词），英文表 v0 只作兜底。
#   ⚠️ 口径校准证据（落版前干跑）：接到 57 份真稿语料上 → **真命中 0 处**；抓到 2 处误报并修掉：
#      `（多留一段腿，好看清比例）` 里的 `好看` 是子串 → 加 (?!清)；
#      无「## 主稿」的回写清单文件不属本脚本适用范围。
# ─────────────────────────────────────────────────────────────
set -u
F="${1:-}"
if [ -z "$F" ]; then echo "用法: bash tools/check-prompt.sh <稿子.md>"; exit 2; fi
if [ ! -f "$F" ]; then echo "找不到文件: $F"; exit 2; fi

# 只取主稿正文：从「## 主稿」起，到判读 / 待回写 / 阶梯类标题止
BODY=$(awk '/^## 主稿/{f=1;next} f&&/^## /&&(/判读/||/待回写/||/待落版/||/待办/||/阶梯/||/若这次/){exit} f' "$F")
[ -z "$BODY" ] && BODY=$(cat "$F")
# v2.19.25.1 修：稿首三行元信息（形态选择 / 下缘声明次数 / 挂档）是**元信息**，不是画面正文 ——
#   ① 的拉丁字母与 ⑪ 的下缘计数都必须排除它们（否则新立的 ⑭ 会把合规矩的稿子自己判死）
BODY=$(printf '%s' "$BODY" | grep -av '^[[:space:]]*\(形态选择\|下缘声明次数\|挂档\)[[:space:]]*[：:]')

fail=0
echo "── 自查：$F"
echo

lat=$(printf '%s' "$BODY" | grep -o '[A-Za-z]' | wc -l | tr -d ' ')
if [ "$lat" -eq 0 ]; then
  echo "✅ ① 拉丁字母 0 处（纯中文政策）"
else
  echo "❌ ① 拉丁字母 $lat 处 —— 必须清零（例外只有模型名与文件名）"
  printf '%s' "$BODY" | grep -n '[A-Za-z]' | head -5
  fail=1
fi

echo
bad=$(printf '%s' "$BODY" | grep -nE '不出现|不要|避免|不写|不做|不得出现|禁止|不追求|不再有|不留|不画|绝不')
# v2.17.0：网撒大 —— 库里实际出现过「不留过渡 / 不画砖缝 / 绝不叠压」这类同义变体（2026-09-19 补入）
if [ -z "$bad" ]; then
  echo "✅ ② 无「禁止式」负向句"
else
  echo "❌ ② 发现禁止式（v2.17.0 起含 不留 / 不画 / 绝不）—— cfg=1.0 下负面词数学上无效、甚至被反转成完成态；一律改陈述式（\"墙上没有任何文字\"）"
  echo "$bad"
  fail=1
fi

echo
# ③ 全称替换句：会被模型**字面执行**、直接删掉人体部位
#    判定：同一「句」里**同时**出现 全称词 与 机械/替换词
# ⚠️ 用 sed 断句（**别用 tr**：tr 按字节处理，会把多字节中文切碎、让 grep 判定为二进制文件而漏报）
whole=$(printf '%s' "$BODY" | sed 's/[。；]/\n/g' | grep -nE '(以下|以上|全部|一律|整个|整条|整只|浑身|全身|完全|所有)' | grep -E '(机械|外骨骼|液压|金属|零件|机甲|义体|替换|换掉|改造|装成)')
if [ -z "$whole" ]; then
  echo "✅ ③ 无「全称替换句」（写着'某处以下是机械'会把那个人体部位整个删掉）"
else
  echo "❌ ③ 发现全称替换句 —— 模型会照字面执行，把那个人体部位**整个删掉**（科幻 v5「肩膀以下是整套机械外骨骼」→ 出图肩以下全是机器）"
  echo "     修法：写成「装甲是穿在她身体外面的壳，壳里是她自己的身体」+「装甲依着她的胸廓 / 腰线 / 腿型走」"
  echo "$whole" | sed 's/^/     /'
  fail=1
fi

echo
# ③b 全称露出 × 遮挡（**跨段**矛盾：一边说"整张脸露在外面"、一边说面罩"横过额头与鼻梁"）
#     判定用两个独立 grep **跨全文**比对（同句检查抓不到跨段矛盾——v7 就是这么翻的）
expose=$(printf '%s' "$BODY" | grep -nE '整张脸|整头|满脸|整条腿|整只手臂|全身[^。；]{0,4}露|整个人[^。；]{0,4}露')
cover=$(printf '%s' "$BODY" | grep -nE '(面罩|面甲|护目片|面具|护面|盔壳)[^。；，、]{0,8}(盖住|遮住|挡住|横过|压在|蒙住)[^。；，、]{0,6}(额头|眼睛|眼|鼻梁|鼻|嘴|脸|半张)')
if [ -z "$expose" ] || [ -z "$cover" ]; then
  echo "✅ ③b 无「全称露出 × 遮挡」跨段矛盾"
else
  echo "❌ ③b 一边说「整张脸 / 整头…露在外面」，一边让面罩／护目片「盖住额头 / 眼 / 鼻梁」 —— 两句跨段互斥，模型会让面罩往上盖，出「机器人头」（科幻 v7 实测）"
  echo "     修法：把遮挡范围写小写实（"护目片只压在两侧额角上、绕到太阳穴，眉、眼、鼻梁与嘴都落在护目片的下方"），或把露出范围写小"
  echo "$cover" | sed 's/^/     /'
  fail=1
fi

echo
# ④ 人物身上的「比…还…」荒谬几何：逼模型把人体缩小去满足它
#    只查**对象是身体部位/身体尺度**的，避免误伤巨构册合法的尺度锚定（"比一个城区还粗"）
# ⚠️ 别用裸的 `比头还` / `比她的头`：`比她的头发暗一档` 会被误判（v2.9.7.1 修）
#    → 身体部位后面加一个"排除字"守卫：头后面跟着 发/盔/顶/盖/部/像/巾 时不算
geo=$(printf '%s' "$BODY" | grep -nE '比[^，。；、）]{0,10}(她的?)?(头[^发盔顶盖部像巾]|身高|身体|人|腰|腿|肩|臂|拳|上半身|整个人)[^，。；]{0,6}(还|更)(粗|宽|大|高|厚|重|长|壮)|超过[^，。；]{0,8}(她的?)?(身高|半个身子|半个人|半身)')
if [ -z "$geo" ]; then
  echo "✅ ④ 人物身上无「比…还…」荒谬几何"
else
  echo "❌ ④ 发现人物身上的荒谬几何 —— 这类句子在几何上与'这是一个人的身体'不相容，模型只能**把人体缩小**（科幻 v5「肩甲总宽超过她的身高 · 腿部装甲比头还粗」→ 部件膨胀、人体缩水）"
  echo "     修法：**体量写成相对她自身身体的可执行倍数**（两片肩甲向外张开、合起来的总宽大约是她肩宽的两倍半），并补一句「人的尺度在装甲外面仍然读得出来」"
  echo "$geo" | sed 's/^/     /'
  fail=1
fi

echo
seg=$(printf '%s' "$BODY" | grep -cE '^\*{0,2}(主体|要点|前景|中景|背景|构图|视觉引导|色调|风格|光影氛围)\*{0,2}：')
if [ "$seg" -eq 10 ]; then
  echo "✅ ⑤ 十段齐（形态 B）"
elif [ "$seg" -eq 0 ]; then
  echo "⚠️ ⑤ 未检出段名 —— 是形态 A（精简长句），还是段名写错了？"
elif [ "$seg" -gt 10 ]; then
  echo "⚠️ ⑤ 检出 $seg 段 —— 多于 10 属正常（含变体 / 漫画册第 11 段「叙事元件」）"
else
  echo "⚠️ ⑤ 只检出 $seg 段（十段式应为 10）—— 数一数漏了哪段"
fi

echo
# ⑥ 手部糊化词（v2.13.0）：把手指"糊在一起"的词，模型照做 → 出蹼 / 团块 / 拇指塌进掌缘
#    只查**手部紧邻**的糊化词，避免误伤"两腿并拢"这类合法几何
#    2026-09-18 实测（①段 1152×2048）：`四指并拢` → 四指连成蹼；`指尖挨着掌心` → 捏针手糊成锥形团块
# ⚠️ ⑥⑦ 都只看**画面正文**：「要点」段是元信息（写给人看的施工说明），不驱动画面的像素
# ⚠️ 手部词表刻意**不含裸的「掌」**：否则"脚掌"会被误认成手（v2.13.0 自查时抓到）
BODYX=$(printf '%s' "$BODY" | grep -av '^[[:space:]]*\**要点')
SENTS=$(printf '%s' "$BODYX" | sed 's/[。；]/\n/g')
HW='(手|指|腕|拇指|食指|掌心)'
glue=$(printf '%s' "$SENTS" | grep -nE "((手指|五指|四指|拇指|食指|指尖|掌心|手)[^，、]{0,3}(并拢|合拢|靠在一起|贴在一起|黏在一起|挤在一起)|(并拢|合拢)[^，、]{0,3}(手指|五指|四指|指尖|手掌)|指尖[^，、]{0,4}挨着掌心)")
# ⚠️ 窗口必须**收到 3 字**：放宽到 8 会把「手腕把伞骨抖开又合拢」（说的是伞骨）误判成手指（v2.13.0 抓到）
# ⚠️ 反向（糊化词在前）也不许用裸的「手」：否则「双脚并拢…并拢垂手」这种**脚部**写法被误判（v2.13.0 抓到）
if [ -z "$glue" ]; then
  echo "✅ ⑥ 手部无「糊化词」"
else
  echo "❌ ⑥ 手部用了糊化词 —— 模型会把手指**糊成一片**（实测：四指连成蹼 · 五指团块 · 拇指塌进掌缘）"
  echo "     修法：把「并拢 / 挨着」改成**张开 + 给指缝里的物**（"五指张开、相邻两根手指之间露着布面"）；蜷起的指头要**彼此分开**、写明指尖**离开**掌心"
  echo "$glue" | sed 's/^/     /'
  fail=1
fi

echo
# ⑦ 手部接触点（v2.13.0）：手 + 物件 + 动作同**句**出现时，**必须写出"谁压谁"**
#    没有接触点 → 模型自己编相对位置 → 手扎进布料 / 道具穿过手指（穿模）
#    ⚠️ 判定必须按**句**、不能按段：段级会让「全身的重量都压在墩面上」这种**无关接触点**
#       把"托着衬衫的手"放行（v2.13.0 自查时抓到，差点装进去）
bad7=$(printf '%s' "$SENTS" | grep -anE "${HW}" \
  | grep -aE '(捏|托|握|按|捧|夹|抓|攥|掐|扶|拿|提|缝|拉|拽|扣|系|端|举|搓|捻)' \
  | grep -aE '(衬衫|布面|布料|布|衣|针|线|扣子|扣眼|剪|杯|伞|刀|笔|绳|箱|碗|盘|书|纸|带|杖|剑|壶|篮|鞋)')
if [ -z "$bad7" ]; then
  echo "✅ ⑦ 无「手 + 物件 + 动作」句（或本稿不涉及手持物）"
else
  # 放行条件 = **关系句式**（谁压谁）或**点名了物件的部件**（前襟 / 柄 / 带尾…）
  #   ⚠️ 光杆的"托着 / 捏着 / 拿着"**不算**——只说明"在拿"，没说明相对几何，正是穿模的成因
  miss=$(printf '%s' "$bad7" | while IFS= read -r l; do
    printf '%s' "$l" | grep -aqE '(压在|压着|搭在|搭着|覆在|覆着|托住|按住|按在|夹在|夹着|垫在|抵在|贴在|搁在|捧住|握住|捏住|抓在|扶着|扶在|隔着|扣在|穿过|绕过|缠|(手|指|拇指|食指|掌心|掌根|指腹|指尖)[^，、]{0,6}之间|(衬衫|布|衣|针|线|伞|杯|刀|笔|杖|剑|壶|篮|箱|包)[^，、]{0,2}(前襟|柄|把手|提手|带尾|带子|边沿|沿口|尾端|鞘口|杯沿))' || printf '%s\n' "$l"
  done)
  if [ -z "$miss" ]; then
    echo "✅ ⑦ 手部动作都写了接触点（谁压谁）"
  else
    echo "❌ ⑦ 有「手 + 物件 + 动作」却没写接触点 —— 模型会自己编相对位置，结果就是**穿模**（实测：手背边缘扎进白衬衫、布面像从手里穿出来）"
    echo "     修法：补一句"谁压谁"——"拇指压在布面上、其余四指从布的下方托住" / "针身夹在指腹与布面之间" / "掌根压在布面上，布边从拇指与食指之间垂下来""
    echo "$miss" | sed 's/^/     /' | cut -c1-200
    fail=1
  fi
fi

echo
echo "ℹ️ ⑧ 陈述式排除项（**唯一有效的排除写法，应保留**）："
printf '%s' "$BODY" | grep -oE '没有[^，。；、）]*|空白[^，。；、）]*' | sed 's/^/     /' | head -8

echo
echo "ℹ️ ⑨ 提醒（人工确认，脚本查不了）："
echo "     · 交付必填两行（**缺 = 没交付完**）："
